import AppKit

/// Borderless button styled as a blue link, opening its URL on click.
/// Replaces the earlier attributed-NSTextField link labels: those carried the
/// `.link` attribute and were selectable, but clicks never fired in this
/// accessory app's About window (confirmed on device 0.10.0 — browser never
/// opened). A button's target/action path has no field-editor dependency.
final class LinkButton: NSButton {
    private let url: URL

    init(text: String, size: CGFloat, url: URL) {
        self.url = url
        super.init(frame: .zero)
        isBordered = false
        attributedTitle = NSAttributedString(
            string: text,
            attributes: [.font: NSFont.systemFont(ofSize: size),
                         .foregroundColor: NSColor.linkColor])
        target = self
        action = #selector(openLink)
        // Pointer affordance: borderless buttons get no cursor change by default.
        let tracking = NSTrackingArea(rect: .zero,
                                      options: [.mouseEnteredAndExited, .activeInKeyWindow, .inVisibleRect],
                                      owner: self)
        addTrackingArea(tracking)
    }

    required init?(coder: NSCoder) { fatalError("LinkButton is built in code only") }

    override func mouseEntered(with event: NSEvent) { NSCursor.pointingHand.push() }
    override func mouseExited(with event: NSEvent) { NSCursor.pop() }

    @objc private func openLink() {
        NSWorkspace.shared.open(url)
    }
}

/// The About mini page (menu: "About DiskLED-plus"). The same page as
/// NeverSleep's and dotbar's: the app icon, the version, the PayPal donation
/// QR (paypal-qr.png in Resources, generated by scripts/make-qr.swift; bundle
/// copy done in make-app.sh), the license and the GitHub repo. Plain AppKit
/// NSWindow — no SwiftUI, matching the rest of the app. Cached so reopening
/// always shows the same window.
final class AboutWindowController: NSObject {
    static let shared = AboutWindowController()
    private var window: NSWindow?

    func show() {
        if window == nil {
            window = buildWindow()
        }
        NSApp.activate(ignoringOtherApps: true)
        window?.center()
        window?.makeKeyAndOrderFront(nil)
    }

    // MARK: - Page construction

    private func buildWindow() -> NSWindow {
        let version = Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "?"
        let build = Bundle.main.infoDictionary?["CFBundleVersion"] as? String ?? "?"

        func label(_ string: String, _ size: CGFloat, _ weight: NSFont.Weight = .regular,
                   _ color: NSColor = .labelColor) -> NSTextField {
            let l = NSTextField(labelWithString: string)
            l.font = .systemFont(ofSize: size, weight: weight)
            l.textColor = color
            l.alignment = .center
            return l
        }

        /// Link rows are NSButtons (LinkButton) — see the class comment.
        func link(_ text: String, _ url: URL, _ size: CGFloat) -> NSView {
            LinkButton(text: text, size: size, url: url)
        }

        func divider() -> NSBox {
            let box = NSBox()
            box.boxType = .separator
            box.widthAnchor.constraint(equalToConstant: 260).isActive = true
            return box
        }

        /// The three donation tiers (0.11.0): coffee (€1), burger (€5), sushi
        /// night (€10) — each opens PayPal.me with the amount prefilled
        /// (paypal.me/<user>/<amount><currency>). Same design as NeverSleep
        /// 0.11 (approved via light/dark mockup).
        func tierRow() -> NSView {
            let row = NSStackView(views: [tierButton("☕️", "€1", "1eur"),
                                          tierButton("🍔", "€5", "5eur"),
                                          tierButton("🍣", "€10", "10eur")])
            row.orientation = .horizontal
            row.spacing = 8
            row.distribution = .fillEqually
            row.widthAnchor.constraint(equalToConstant: 252).isActive = true
            return row
        }

        func tierButton(_ emoji: String, _ amount: String, _ path: String) -> NSView {
            let b = TierButton(url: URL(string: "https://paypal.me/marcodalmoro/\(path)")!)
            let para = NSMutableParagraphStyle()
            para.alignment = .center
            let text = NSMutableAttributedString()
            text.append(NSAttributedString(string: emoji + "\n", attributes: [
                .font: NSFont.systemFont(ofSize: 17),
            ]))
            text.append(NSAttributedString(string: amount, attributes: [
                .font: NSFont.boldSystemFont(ofSize: 12),
                .foregroundColor: NSColor.white,
                .paragraphStyle: para,
            ]))
            b.attributedTitle = text
            b.setAccessibilityLabel("Donate \(amount) via PayPal")
            b.heightAnchor.constraint(equalToConstant: 46).isActive = true
            return b
        }

        // Symbol badge helper: an SF Symbol image at a given size, tinted
        // (contentTintColor — works in windows; the NSMenuItem.image quirk
        // doesn't apply here).
        func symbol(_ name: String, size: CGFloat, tint: NSColor) -> NSView {
            let image = NSImage(systemSymbolName: name, accessibilityDescription: name)?
                .withSymbolConfiguration(.init(pointSize: size, weight: .regular))
            let v = NSImageView(image: image ?? NSImage())
            v.contentTintColor = tint
            v.widthAnchor.constraint(equalToConstant: size + 2).isActive = true
            v.heightAnchor.constraint(equalToConstant: size).isActive = true
            return v
        }

        /// Card container — the heat-warning panel's card pattern (NeverSleep
        /// 0.14/0.15): badge + bold title on top, content below, soft rounded
        /// background.
        func card(badge: String, tint: NSColor, title: String, _ content: NSView) -> NSView {
            let header = NSStackView(views: [symbol(badge, size: 13, tint: tint),
                                             label(title, 13, .semibold)])
            header.orientation = .horizontal
            header.spacing = 8
            header.alignment = .centerY
            let stack = NSStackView(views: [header, content])
            stack.orientation = .vertical
            stack.spacing = 10
            stack.alignment = .leading
            stack.edgeInsets = NSEdgeInsets(top: 12, left: 12, bottom: 12, right: 12)
            stack.wantsLayer = true
            stack.layer?.backgroundColor = NSColor.labelColor.withAlphaComponent(0.03).cgColor
            stack.layer?.cornerRadius = 10
            stack.widthAnchor.constraint(equalToConstant: 276).isActive = true
            return stack
        }

        // App icon (52 pt) — the icns from Resources; the bare binary gets
        // macOS's generic icon instead, same as before the bundled app.
        let icon = NSImageView(image: NSApp.applicationIconImage)
        icon.widthAnchor.constraint(equalToConstant: 52).isActive = true
        icon.heightAnchor.constraint(equalToConstant: 52).isActive = true

        // Header: icon + name + version, leading-aligned (0.11.0 card style).
        let nameColumn = NSStackView(views: [
            label("DiskLED-plus", 22, .bold),
            label("Version \(version) (build \(build))", 11, .regular, .secondaryLabelColor),
        ])
        nameColumn.orientation = .vertical
        nameColumn.spacing = 3
        nameColumn.alignment = .leading
        let header = NSStackView(views: [icon, nameColumn])
        header.orientation = .horizontal
        header.spacing = 14
        header.alignment = .centerY

        // Donation block: PayPal.me QR + tappable link (phones can't scan
        // their own screen, so the link matters). QR is bundled as
        // paypal-qr.png; when absent (bare `swift build`, no bundle) the
        // block degrades to text.
        let qrImage = Bundle.main.url(forResource: "paypal-qr", withExtension: "png")
            .flatMap { NSImage(contentsOf: $0) }
        var qrView: NSImageView?
        if let qrImage {
            let v = NSImageView(image: qrImage)
            v.imageScaling = .scaleProportionallyUpOrDown
            v.widthAnchor.constraint(equalToConstant: 88).isActive = true
            v.heightAnchor.constraint(equalToConstant: 88).isActive = true
            v.setAccessibilityLabel("PayPal donation QR code")
            qrView = v
        }

        let supportContent = NSStackView(views: [])
        supportContent.orientation = .vertical
        supportContent.spacing = 10
        supportContent.alignment = .centerX
        var supportViews: [NSView] = []
        if let qrView { supportViews.append(qrView) }
        supportViews.append(contentsOf: [
            tierRow(),
            link("paypal.me/marcodalmoro", URL(string: "https://paypal.me/marcodalmoro")!, 11),
        ])
        let caption = label(
            "Scan the code, tap the link, or pick a coffee — a coffee (€1), a burger (€5), a sushi night (€10). Thank you!",
            10, .regular, .secondaryLabelColor)
        caption.lineBreakMode = .byWordWrapping
        caption.preferredMaxLayoutWidth = 228
        supportViews.append(caption)
        supportViews.forEach { supportContent.addArrangedSubview($0) }

        let bugContent = link("github.com/Marcus1571/diskled-plus/issues",
                              URL(string: "https://github.com/Marcus1571/diskled-plus/issues")!, 11)

        let licenseContent = NSStackView(views: [
            label("© 2026 Marcus1571", 11),
            label("MIT", 11, .regular, .secondaryLabelColor),
            link("github.com/Marcus1571/diskled-plus",
                 URL(string: "https://github.com/Marcus1571/diskled-plus")!, 11),
        ])
        licenseContent.orientation = .vertical
        licenseContent.spacing = 6
        licenseContent.alignment = .leading

        let tagline = label(
            "Disk activity, shown the way hardware used to do it: one LED per channel, "
            + "blinking for every single tick of I/O — 33 times per second, nothing "
            + "averaged, nothing rounded up, nothing smoothed away.",
            11, .regular, .secondaryLabelColor)
        tagline.lineBreakMode = .byWordWrapping
        tagline.preferredMaxLayoutWidth = 252

        var views: [NSView] = [
            header,
            card(badge: "heart.fill", tint: .controlAccentColor, title: "Support DiskLED-plus", supportContent),
            card(badge: "ladybug.fill", tint: .systemOrange, title: "Report a Bug", bugContent),
            card(badge: "doc.text", tint: .secondaryLabelColor, title: "License & code", licenseContent),
            divider(),
            tagline,
        ]

        let stack = NSStackView(views: views)
        stack.orientation = .vertical
        stack.spacing = 12
        stack.alignment = .leading
        stack.edgeInsets = NSEdgeInsets(top: 20, left: 20, bottom: 20, right: 20)

        let w = NSWindow(contentRect: NSRect(x: 0, y: 0, width: 316, height: stack.fittingSize.height),
                         styleMask: [.titled, .closable], backing: .buffered, defer: false)
        w.title = "About DiskLED-plus"
        w.isReleasedWhenClosed = false
        w.contentView = stack
        return w
    }

    /// The bug-report section: folded into the Report a Bug card (0.12.0) —
    /// the standalone bugRow/symbolLabel helpers are gone.
}

/// Blue pill button for a donation tier; opens its PayPal.me amount URL in
/// the default browser. Tier design shared with NeverSleep 0.11 / usagebar
/// 0.10 / dotbar (mac-menu-bar-apps About standard).
final class TierButton: NSButton {
    private let url: URL

    init(url: URL) {
        self.url = url
        super.init(frame: .zero)
        isBordered = false
        wantsLayer = true
        layer?.backgroundColor = NSColor(red: 0.0, green: 0.41, blue: 0.77, alpha: 1).cgColor
        layer?.cornerRadius = 9
        target = self
        action = #selector(openURL(_:))
    }

    required init?(coder: NSCoder) {
        fatalError("init(coder:) is not supported")
    }

    @objc private func openURL(_ sender: Any) {
        NSWorkspace.shared.open(url)
    }
}
